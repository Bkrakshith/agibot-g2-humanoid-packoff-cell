"""Per-episode scene variant for reset mode "restart" (pure, no ROS / no pxr needed).

Genie Sim's RT engine has no reset or teleport service (its ROS node only subscribes /joint_command,
/cmd_4ws and the viewer camera pose; checked in genie_sim_engine/src/realtime_ros_node.cpp @6ca11c7),
so the supported way to put the bags somewhere else is to start the sim on a different scene USD.
write_variant() writes:
  <out_dir>/<name>.usda  a thin layer: subLayers = [cell.usda] + `over` the bag xforms
  <out_dir>/<name>.yaml  the base scene YAML with `scene:` pointing at that layer (absolute path)
The physics stage and the OVRTX render stage both open the layer, so the head camera sees the bags
where physics put them.
"""
from __future__ import annotations

import os
import re
from pathlib import Path


def _num(v: float) -> str:
    return f"{float(v):.6g}"


def override_usda(sublayer: str, poses: dict, comment: str = "") -> str:
    """poses: bag prim name under /World/Bags -> (x, y, yaw_deg, z_bottom)."""
    lines = ["#usda 1.0", "(",
             f'    "Generated by g2cell_datagen.scene_variant{": " + comment if comment else ""}"',
             '    defaultPrim = "World"', "    metersPerUnit = 1", '    upAxis = "Z"',
             "    subLayers = [", f"        @{sublayer}@", "    ]", ")", "",
             'over "World"', "{", '    over "Bags"', "    {"]
    for name in sorted(poses):
        x, y, yaw, z = poses[name]
        lines += [f'        over "{name}"', "        {",
                  f"            float xformOp:rotateZ = {_num(yaw)}",
                  f"            double3 xformOp:translate = ({_num(x)}, {_num(y)}, {_num(z)})",
                  "        }"]
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def scene_yaml(base_text: str, scene_path: str, comment: str = "") -> str:
    out, n = re.subn(r"(?m)^scene:.*$", f"scene: {scene_path}", base_text)
    if n != 1:
        raise ValueError(f"base scene YAML must have exactly one top-level 'scene:' line (found {n})")
    head = f"# g2cell_datagen variant{': ' + comment if comment else ''}\n" if comment else ""
    return head + out


def write_variant(base_yaml, cell_usda, out_dir, name: str, poses: dict, comment: str = ""):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    usda = out_dir / f"{name}.usda"
    rel = os.path.relpath(Path(cell_usda).resolve(), out_dir.resolve())
    usda.write_text(override_usda(rel, poses, comment))
    yml = out_dir / f"{name}.yaml"
    yml.write_text(scene_yaml(Path(base_yaml).read_text(), str(usda), comment))
    return usda, yml
